/**
 * Embed paper PDFs into the worker bundle.
 *
 * Google Scholar's individual-author route wants the full text in a real .pdf,
 * and `citation_pdf_url` must name a file in the SAME subdirectory as the HTML.
 * Serving from static.radioindex.org would silently break indexing, so the bytes
 * ride in the bundle and the worker serves them from /paper/{slug}.pdf.
 *
 * Usage: node scripts/paper-pdf-embed.mjs
 * Reads papers/*.pdf, writes src/generated/paper-pdfs.ts
 */
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { join } from "node:path";

const PAPERS = "papers";
const OUT_DIR = "src/generated";
const OUT = join(OUT_DIR, "paper-pdfs.ts");

if (!existsSync(OUT_DIR)) mkdirSync(OUT_DIR, { recursive: true });

const files = existsSync(PAPERS)
  ? readdirSync(PAPERS).filter((f) => f.endsWith(".pdf"))
  : [];

const entries = files.map((f) => {
  const bytes = readFileSync(join(PAPERS, f));
  // A PDF that is not a PDF would be indexed as a broken record, so check the magic.
  if (bytes.subarray(0, 5).toString("latin1") !== "%PDF-") {
    console.error(`${f} is not a PDF (bad magic) — refusing to embed`);
    process.exit(1);
  }
  return { slug: f.replace(/\.pdf$/, ""), b64: bytes.toString("base64"), size: bytes.length };
});

const lines = [
  "// AUTO-GENERATED by scripts/paper-pdf-embed.mjs - DO NOT EDIT",
  "// Base64 so the bytes travel in the worker bundle. Scholar requires the PDF to",
  "// sit in the same subdirectory as the HTML it belongs to.",
  "export const PAPER_PDFS: Record<string, string> = {",
  ...entries.map((e) => `  ${JSON.stringify(e.slug)}: ${JSON.stringify(e.b64)},`),
  "};",
  "",
];
writeFileSync(OUT, lines.join("\n"));

for (const e of entries) {
  console.log(`  ${e.slug}.pdf  ${e.size.toLocaleString()} bytes`);
}
console.log(`${OUT}: ${entries.length} pdf(s)`);
